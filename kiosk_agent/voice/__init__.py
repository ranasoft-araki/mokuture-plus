"""音声入力（QR無し来訪者の受付フォームを声で埋める実験機能）。

キオスク端末の中で完結する。音声・氏名・会社名を外部へ送らない。クラウドの音声認識
API も Web Speech API も生成 AI も使わない。ネットワークが切れていても動く。

名刺読み取り（`card/`）と違い、**マイクを握るのはブラウザではなくこのサービス**である
（要件 §10）。ブラウザは「いま何を入力しているか」と「話してください」の案内を描き、
録音・VAD・認識はすべてここで行う。

キオスク本体（`main.py` / port 8080 / 0.0.0.0）とは**別プロセス・別ポート**で動かす:

  - `127.0.0.1:8181` だけに bind する。本体は端末管理のため 0.0.0.0 で待ち受けている
    ので、そこへ相乗りすると音声 API が LAN から見えてしまう。ソケットの時点で閉じる。
  - 実験機能が落ちても受付（GPIO・ロッカー・扉）を巻き込まない。systemd
    (`mokuture-voice.service`, Restart=always) が音声だけを復帰させ、画面からは
    「音声で入力」ボタンが消えるだけで受付は続けられる。
  - whisper.cpp は CPU を数秒占有する。本体と分けておくと相互影響が読みやすい。

コードは `kiosk_agent/` 配下にあるので OTA で配信できる（`updater.py` の MANAGED_FILES）。
配信されたあと自プロセスのソース hash の変化を検知して自ら終了し、systemd に拾わせる
（`server.py` の watch_sources）。

ディスクに残すもの / 残さないもの:

  - 音声は**メモリ上だけ**。whisper.cpp に渡す WAV は tmpfs(`/dev/shm`)へ書き、認識・
    キャンセル・タイムアウトのいずれでも finally で必ず消す。
  - 認識したテキスト（＝氏名・会社名）はセッションのメモリにだけ置き、ログにも
    メトリクスにも書かない。破棄はセッション終了時。
  - 実験用メトリクスは個人を特定できない数値だけ（`metrics.py`）。
"""
